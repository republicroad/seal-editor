import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { CORPUS_FILES, parseCorpusFile } from './zen-corpus.mjs';

/**
 * zen 表达式函数速查生成器——jdm 回归语料的机械投影（docs/zen-function-reference.md）。
 * 语料更新后重跑即同步；产物带 generated 头，勿手改。
 *
 * Usage: node scripts/gen-zen-function-reference.mjs [--corpus <dir>] [--check]
 *   --check  只校验产物是否为最新（与重生成 diff），不写文件
 */

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outPath = path.join(root, 'docs', 'zen-function-reference.md');
const defaultCorpus = path.join(root, '..', 'jdm-editor', 'packages', 'zen-udf', 'src', 'expression-regression');

const args = process.argv.slice(2);
const checkOnly = args.includes('--check');
const corpusArgIdx = args.indexOf('--corpus');
const corpusDir = corpusArgIdx >= 0 ? args[corpusArgIdx + 1] : defaultCorpus;

if (!existsSync(corpusDir)) {
  console.error(`[gen-fn-ref] 语料目录不存在：${corpusDir}（--corpus 指定或检出同级 jdm-editor 仓）`);
  process.exit(1);
}

/** 表格代码单元：按内容中最长反引号串动态加厚定界符；表格竖管转义 */
const codeCell = (text) => {
  const maxRun = Math.max(0, ...(text.match(/`+/g) ?? []).map((r) => r.length));
  const fence = '`'.repeat(maxRun + 1);
  const pad = fence.length > 1 ? ' ' : '';
  return `${fence}${pad}${text.replaceAll('|', '\\|')}${pad}${fence}`;
};

const sections = [];
let totalRows = 0;
let totalSkipped = 0;

for (const file of CORPUS_FILES) {
  const { rows, skipped } = parseCorpusFile(corpusDir, file);
  totalRows += rows.length;
  totalSkipped += skipped;
  // 节结构：parseCorpusText 剥掉了 `# 节` 注释行，这里按原文行扫描重建归属
  const fileSections = [];
  const sectionOf = new Map();
  const raw = readFileSync(path.join(corpusDir, file), 'utf8').split(/\r?\n/);
  let current = null;
  raw.forEach((line, index) => {
    const trimmed = line.trim();
    if (trimmed.startsWith('#')) {
      current = trimmed.replace(/^#\s*/, '');
      return;
    }
    const row = rows.find((r) => r.line === index + 1);
    if (!row) return;
    const key = current ?? '(unsectioned)';
    if (!sectionOf.has(key)) sectionOf.set(key, []);
    sectionOf.get(key).push(row);
  });
  for (const [name, sectionRows] of sectionOf) {
    fileSections.push({ name, rows: sectionRows });
  }
  sections.push({ file, sections: fileSections, skipped });
}

const lines = [];
lines.push(
  '<!-- generated by scripts/gen-zen-function-reference.mjs — DO NOT EDIT / 本档由生成器产出，勿手改；语料更新后重跑即同步 -->',
);
lines.push('');
lines.push('# Zen Function Reference (generated)');
lines.push('');
lines.push('全量可执行断言速查 / Full executable-assertion quick reference——源语料 jdm-editor 仓');
lines.push('`packages/zen-udf/src/expression-regression/{standard,date,unary}.csv`。');
lines.push('');
lines.push(`- 断言行 / assertion rows: **${totalRows}**（非 3 字段行跳过 / skipped: ${totalSkipped}）`);
lines.push('- 重生成 / regenerate: `node scripts/gen-zen-function-reference.mjs`（`--corpus` 指定语料目录）');
lines.push('- 验证 / verify: `node scripts/probes/zen-reference-verify.mjs --full`');
lines.push('- 语义总表 / semantics: [zen-reference](./zen-reference)');
lines.push('');

for (const { file, sections: fileSections, skipped } of sections) {
  const rowCount = fileSections.reduce((sum, s) => sum + s.rows.length, 0);
  lines.push(`## ${file} · ${rowCount} rows`);
  lines.push('');
  for (const { name, rows: sectionRows } of fileSections) {
    lines.push(`### ${name}`);
    lines.push('');
    lines.push('| expression | input | output |');
    lines.push('| --- | --- | --- |');
    for (const row of sectionRows) {
      lines.push(`| ${codeCell(row.expression)} | ${row.input ? codeCell(row.input) : ''} | ${codeCell(row.output)} |`);
    }
    lines.push('');
  }
  if (skipped > 0) {
    lines.push(`> ${skipped} rows skipped (non-3-field separator lines, mirrors jdm parser).`);
    lines.push('');
  }
}

const output =
  lines
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd() + '\n';

if (checkOnly) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (current === output) {
    console.log(`[gen-fn-ref] ✓ 产物为最新（${totalRows} 行断言）`);
    process.exit(0);
  }
  console.error('[gen-fn-ref] ✗ 产物过期——重跑 node scripts/gen-zen-function-reference.mjs');
  process.exit(1);
}

writeFileSync(outPath, output, 'utf8');

// 产物必须过仓库 prettier 门禁——生成即格式化，保证幂等
const prettier = spawnSync('npx', ['prettier', '--write', outPath], {
  encoding: 'utf8',
  shell: process.platform === 'win32',
});
if (prettier.status !== 0) {
  console.error('[gen-fn-ref] prettier failed:\n' + prettier.stderr);
  process.exit(1);
}

console.log(`[gen-fn-ref] ✓ ${outPath}（${totalRows} 行断言，跳过 ${totalSkipped}）`);
